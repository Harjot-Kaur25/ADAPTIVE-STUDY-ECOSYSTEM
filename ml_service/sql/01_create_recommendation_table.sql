-- This is the only supplemental project table created by the ML component.
-- Run 00_verify_existing_schema.sql first. Existing tables are never dropped
-- or recreated. IDs are stored as text here because the shared schema summary
-- did not specify the source ID datatypes; the Python service checks actual
-- STUDENT/SUBJECT ID column types before binding their upserts.
SET SERVEROUTPUT ON

DECLARE
    v_count PLS_INTEGER;
    v_missing VARCHAR2(4000);
BEGIN
    FOR source_column IN (
        SELECT 'STUDENT' table_name, 'STUDENT_ID' column_name FROM dual UNION ALL
        SELECT 'STUDENT', 'STUDENT_NAME' FROM dual UNION ALL
        SELECT 'SUBJECT', 'SUBJECT_ID' FROM dual UNION ALL
        SELECT 'SUBJECT', 'SUBJECT_NAME' FROM dual
    ) LOOP
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = source_column.table_name
           AND COLUMN_NAME = source_column.column_name;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20010,
                'Existing ' || source_column.table_name || '.' ||
                source_column.column_name || ' is required before creating recommendation storage.'
            );
        END IF;
    END LOOP;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS c
      JOIN USER_CONS_COLUMNS cc
        ON cc.constraint_name = c.constraint_name
       AND cc.table_name = c.table_name
     WHERE c.constraint_type = 'P'
       AND c.table_name = 'STUDENT'
       AND cc.column_name = 'STUDENT_ID'
       AND (SELECT COUNT(*) FROM USER_CONS_COLUMNS all_cc
             WHERE all_cc.constraint_name = c.constraint_name
               AND all_cc.table_name = c.table_name) = 1;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20013, 'STUDENT.STUDENT_ID must be its single-column primary key.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS c
      JOIN USER_CONS_COLUMNS cc
        ON cc.constraint_name = c.constraint_name
       AND cc.table_name = c.table_name
     WHERE c.constraint_type = 'P'
       AND c.table_name = 'SUBJECT'
       AND cc.column_name = 'SUBJECT_ID'
       AND (SELECT COUNT(*) FROM USER_CONS_COLUMNS all_cc
             WHERE all_cc.constraint_name = c.constraint_name
               AND all_cc.table_name = c.table_name) = 1;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20014, 'SUBJECT.SUBJECT_ID must be its single-column primary key.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'STUDY_RECOMMENDATION';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE STUDY_RECOMMENDATION (
                recommendation_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
                student_id VARCHAR2(128) NOT NULL,
                student_name VARCHAR2(200) NOT NULL,
                subject_id VARCHAR2(128) NOT NULL,
                subject_name VARCHAR2(200) NOT NULL,
                average_marks NUMBER(5,2) NOT NULL,
                exam_count NUMBER(5) NOT NULL,
                total_study_hours NUMBER(7,2) NOT NULL,
                completed_sessions NUMBER(6) NOT NULL,
                missed_sessions NUMBER(6) NOT NULL,
                upcoming_exam_date DATE,
                days_remaining NUMBER(4),
                priority VARCHAR2(10) NOT NULL,
                score_high NUMBER(9,8) NOT NULL,
                score_medium NUMBER(9,8) NOT NULL,
                score_low NUMBER(9,8) NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT study_recommendation_pk PRIMARY KEY (recommendation_id),
                CONSTRAINT study_recommendation_priority_ck
                    CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW'))
            )
        ]';
        DBMS_OUTPUT.PUT_LINE('Created STUDY_RECOMMENDATION.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('STUDY_RECOMMENDATION already exists; checking its structure.');
    END IF;

    FOR required_column IN (
        SELECT column_name
          FROM (
              SELECT 'RECOMMENDATION_ID' column_name FROM dual UNION ALL
              SELECT 'STUDENT_ID' FROM dual UNION ALL
              SELECT 'STUDENT_NAME' FROM dual UNION ALL
              SELECT 'SUBJECT_ID' FROM dual UNION ALL
              SELECT 'SUBJECT_NAME' FROM dual UNION ALL
              SELECT 'AVERAGE_MARKS' FROM dual UNION ALL
              SELECT 'EXAM_COUNT' FROM dual UNION ALL
              SELECT 'TOTAL_STUDY_HOURS' FROM dual UNION ALL
              SELECT 'COMPLETED_SESSIONS' FROM dual UNION ALL
              SELECT 'MISSED_SESSIONS' FROM dual UNION ALL
              SELECT 'UPCOMING_EXAM_DATE' FROM dual UNION ALL
              SELECT 'DAYS_REMAINING' FROM dual UNION ALL
              SELECT 'PRIORITY' FROM dual UNION ALL
              SELECT 'SCORE_HIGH' FROM dual UNION ALL
              SELECT 'SCORE_MEDIUM' FROM dual UNION ALL
              SELECT 'SCORE_LOW' FROM dual
          )
    ) LOOP
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'STUDY_RECOMMENDATION'
           AND COLUMN_NAME = required_column.column_name;
        IF v_count = 0 THEN
            v_missing := v_missing || CASE WHEN v_missing IS NULL THEN '' ELSE ', ' END
                         || required_column.column_name;
        END IF;
    END LOOP;

    IF v_missing IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(
            -20011, 'Existing STUDY_RECOMMENDATION is missing: ' || v_missing
        );
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM USER_CONSTRAINTS c
      JOIN USER_CONS_COLUMNS cc
        ON cc.constraint_name = c.constraint_name
       AND cc.table_name = c.table_name
     WHERE c.constraint_type = 'P'
       AND c.table_name = 'STUDY_RECOMMENDATION'
       AND cc.column_name = 'RECOMMENDATION_ID'
       AND (SELECT COUNT(*) FROM USER_CONS_COLUMNS all_cc
             WHERE all_cc.constraint_name = c.constraint_name
               AND all_cc.table_name = c.table_name) = 1;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20012, 'STUDY_RECOMMENDATION.RECOMMENDATION_ID must be its single-column primary key.'
        );
    END IF;
    DBMS_OUTPUT.PUT_LINE('STUDY_RECOMMENDATION structure verified.');
END;
