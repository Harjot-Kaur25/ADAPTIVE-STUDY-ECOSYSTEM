CREATE TABLE IF NOT EXISTS public.study_preferences (
    student_id text PRIMARY KEY,
    preferred_session text NOT NULL
        CHECK (preferred_session IN ('1h', '2h', '2-3h')),
    break_minutes integer NOT NULL DEFAULT 10
        CHECK (break_minutes BETWEEN 0 AND 60),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.resource_recommendations (
    recommendation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id text NOT NULL REFERENCES public.students(student_id) ON DELETE CASCADE,
    subject_id text NOT NULL REFERENCES public.subjects(subject_id) ON DELETE CASCADE,
    topic text,
    provider text NOT NULL,
    resource_type text NOT NULL,
    search_query text NOT NULL,
    priority_context text CHECK (priority_context IN ('HIGH', 'MEDIUM', 'LOW')),
    recommended_at timestamptz NOT NULL DEFAULT now()
);

-- Upserts and duplicate-session prevention require these natural-key indexes.
-- PostgreSQL reports existing duplicate records rather than discarding them.
CREATE UNIQUE INDEX IF NOT EXISTS student_subjects_student_subject_uidx
    ON public.student_subjects (student_id, subject_id);

CREATE UNIQUE INDEX IF NOT EXISTS student_availability_period_uidx
    ON public.student_availability (student_id, day_of_week, start_time, end_time);

CREATE UNIQUE INDEX IF NOT EXISTS subject_priorities_student_subject_uidx
    ON public.subject_priorities (student_id, subject_id);

CREATE UNIQUE INDEX IF NOT EXISTS study_sessions_slot_uidx
    ON public.study_sessions (student_id, subject_id, session_date, start_time, end_time);

CREATE UNIQUE INDEX IF NOT EXISTS students_auth_user_uidx
    ON public.students (auth_user_id)
    WHERE auth_user_id IS NOT NULL;

